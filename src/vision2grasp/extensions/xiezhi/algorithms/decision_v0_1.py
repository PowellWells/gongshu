"""Formal Xiezhi Decision v0.1 threshold algorithm.

Pipeline: Observation -> Candidate Evaluation -> Risk Assessment ->
Decision Selection -> AlgorithmDecision v1 output.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import isfinite
from uuid import uuid4

from vision2grasp.intelligence.blueprint import (
    AlgorithmBlueprint,
    AlgorithmMetadata,
    AlgorithmStatus,
    AlgorithmType,
    BlueprintStage,
)
from vision2grasp.intelligence.contracts import (
    INTELLIGENCE_DECISION_SCHEMA_VERSION,
    AlgorithmDecision,
    AlgorithmObservation,
    CandidateEvidence,
    DecisionAction,
    DecisionStatus,
)


XIEZHI_DECISION_V0_1_ID = "xiezhi_decision_v0_1"
XIEZHI_DECISION_V0_1_VERSION = "v0.1"
_STAGE_IDS = (
    "observation",
    "candidate_evaluation",
    "risk_assessment",
    "decision_selection",
    "decision_output",
)


@dataclass(frozen=True, slots=True)
class XiezhiDecisionV01Config:
    max_position_std_m: float = 0.020
    max_rotation_std_rad: float = 0.12
    min_candidate_score: float = 0.75

    def __post_init__(self) -> None:
        for name in ("max_position_std_m", "max_rotation_std_rad"):
            value = getattr(self, name)
            if not isfinite(value) or value < 0:
                raise ValueError(f"{name} must be finite and non-negative")
        if not isfinite(self.min_candidate_score) or not 0 <= self.min_candidate_score <= 1:
            raise ValueError("min_candidate_score must be in [0, 1]")


@dataclass(frozen=True, slots=True)
class CandidateEvaluation:
    candidate_id: str
    planner_score: float
    evidence_confidence: float | None
    decision_score: float
    executable: bool

    def public_metadata(self) -> dict[str, object]:
        return {
            "candidate_id": self.candidate_id,
            "planner_score": self.planner_score,
            "evidence_confidence": self.evidence_confidence,
            "decision_score": self.decision_score,
            "executable": self.executable,
        }


@dataclass(frozen=True, slots=True)
class RiskAssessment:
    candidate_id: str | None
    risk_estimation: float | None
    position_std_proxy_m: float | None
    rotation_std_proxy_rad: float | None
    acceptable: bool
    reasons: tuple[str, ...]

    def public_metadata(self) -> dict[str, object]:
        return {
            "candidate_id": self.candidate_id,
            "risk_estimation": self.risk_estimation,
            "position_std_proxy_m": self.position_std_proxy_m,
            "rotation_std_proxy_rad": self.rotation_std_proxy_rad,
            "acceptable": self.acceptable,
            "reasons": list(self.reasons),
        }


@dataclass(frozen=True, slots=True)
class DecisionSelection:
    action: DecisionAction
    selected_candidate_id: str | None
    reason: str

    def public_metadata(self) -> dict[str, str | None]:
        return {
            "action": self.action.value,
            "selected_candidate_id": self.selected_candidate_id,
            "reason": self.reason,
        }


