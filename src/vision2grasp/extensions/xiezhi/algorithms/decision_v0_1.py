class XiezhiDecisionV01:
    """Deterministic, inspectable v0.1 decision authority."""

    metadata = XIEZHI_DECISION_V0_1_METADATA
    blueprint = XIEZHI_DECISION_V0_1_BLUEPRINT

    def __init__(self, config: XiezhiDecisionV01Config = XiezhiDecisionV01Config()) -> None:
        self.config = config

    @staticmethod
    def observe(observation: AlgorithmObservation) -> AlgorithmObservation:
        if not isinstance(observation, AlgorithmObservation):
            raise TypeError("Xiezhi Decision v0.1 requires AlgorithmObservation")
        return observation

    @staticmethod
    def _decision_score(candidate: CandidateEvidence, confidence: float | None) -> float:
        if confidence is None:
            return float(candidate.score)
        return float((candidate.score + confidence) / 2.0)

    def evaluate_candidates(
        self, observation: AlgorithmObservation
    ) -> tuple[CandidateEvaluation, ...]:
        evaluations = (
            CandidateEvaluation(
                candidate_id=candidate.candidate_id,
                planner_score=float(candidate.score),
                evidence_confidence=observation.evidence_confidence,
                decision_score=self._decision_score(candidate, observation.evidence_confidence),
                executable=candidate.executable,
            )
            for candidate in observation.candidates
            if candidate.executable
        )
        return tuple(sorted(evaluations, key=lambda item: item.decision_score, reverse=True))

    def assess_risk(
        self,
        observation: AlgorithmObservation,
        evaluations: tuple[CandidateEvaluation, ...],
    ) -> RiskAssessment:
        confidence = observation.evidence_confidence
        position_std = None if confidence is None else 0.004 + (1.0 - confidence) * 0.032
        rotation_std = None if confidence is None else 0.03 + (1.0 - confidence) * 0.18
        selected = evaluations[0] if evaluations else None
        reasons: list[str] = []
        if selected is None:
            reasons.append("NO_EXECUTABLE_CANDIDATE")
        if position_std is None:
            reasons.append("POSITION_UNCERTAINTY_UNKNOWN")
        elif position_std > self.config.max_position_std_m:
            reasons.append("POSITION_UNCERTAINTY_HIGH")
        if rotation_std is None:
            reasons.append("ROTATION_UNCERTAINTY_UNKNOWN")
        elif rotation_std > self.config.max_rotation_std_rad:
            reasons.append("ROTATION_UNCERTAINTY_HIGH")
        if selected is not None and selected.decision_score < self.config.min_candidate_score:
            reasons.append("CANDIDATE_SCORE_LOW")
        return RiskAssessment(
            candidate_id=None if selected is None else selected.candidate_id,
            risk_estimation=None if selected is None else float(1.0 - selected.decision_score),
            position_std_proxy_m=position_std,
            rotation_std_proxy_rad=rotation_std,
            acceptable=not reasons,
            reasons=tuple(reasons),
        )

    @staticmethod
    def select_decision(risk: RiskAssessment) -> DecisionSelection:
        if risk.acceptable and risk.candidate_id is not None:
            return DecisionSelection(
                DecisionAction.EXECUTE_GRASP,
                risk.candidate_id,
                "uncertainty_and_quality_acceptable",
            )
        return DecisionSelection(
            DecisionAction.REOBSERVE,
            None,
            "uncertainty_unknown_or_high_or_candidate_poor",
        )

    def output_decision(
        self,
        observation: AlgorithmObservation,
        evaluations: tuple[CandidateEvaluation, ...],
        risk: RiskAssessment,
        selection: DecisionSelection,
    ) -> AlgorithmDecision:
        strongest = evaluations[0] if evaluations else None
        uncertainty = tuple(dict.fromkeys((*observation.uncertainty_reasons, *risk.reasons)))
        return AlgorithmDecision(
            decision_id=f"decision-{uuid4().hex[:16]}",
            observation_id=observation.observation_id,
            provider_id=self.metadata.provider_id,
            algorithm_id=self.metadata.algorithm_id,
            status=DecisionStatus.ACTION_AVAILABLE,
            selected_action=selection.action,
            selected_candidate_id=selection.selected_candidate_id,
            confidence=(
                observation.evidence_confidence
                if strongest is None
                else strongest.decision_score
            ),
            risk_estimation=risk.risk_estimation,
            reason=selection.reason,
            uncertainty=uncertainty,
            diagnostics={
                "algorithm": self.metadata.public_metadata(),
                "blueprint_id": self.blueprint.blueprint_id,
                "pipeline_stages": list(self.metadata.stages),
                "candidate_evaluations": [item.public_metadata() for item in evaluations],
                "risk_assessment": risk.public_metadata(),
                "decision_selection": selection.public_metadata(),
                "provider_score_type": "MEAN_PLANNER_RANKING_AND_EVIDENCE_CONFIDENCE",
            },
        )

    def decide(self, observation: AlgorithmObservation) -> AlgorithmDecision:
        observed = self.observe(observation)
        evaluations = self.evaluate_candidates(observed)
        risk = self.assess_risk(observed, evaluations)
        selection = self.select_decision(risk)
        return self.output_decision(observed, evaluations, risk, selection)


